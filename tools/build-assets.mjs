// Bundles /public into src/generated/assets.ts so the Worker can serve the site itself.
// (Workers Static Assets is the usual route; this environment's network proxy blocks the asset
//  upload step, and serving a ~150 KB bundle from the Worker costs the same tiny request fee.)
import { readdirSync, readFileSync, writeFileSync, mkdirSync, statSync } from "node:fs";
import { join, extname } from "node:path";

const TYPES = { ".html": "text/html; charset=utf-8", ".css": "text/css; charset=utf-8", ".js": "text/javascript; charset=utf-8", ".json": "application/json", ".svg": "image/svg+xml" };
const files = {};
const walk = (dir, base = "") => {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p, `${base}/${name}`);
    else if (name.endsWith(".d.ts")) continue; // type declarations are for the server build, not the site
    else files[`${base}/${name}`] = { type: TYPES[extname(name)] ?? "application/octet-stream", body: readFileSync(p, "utf8") };
  }
};
walk("public");
mkdirSync("src/generated", { recursive: true });
writeFileSync("src/generated/assets.ts", `// Generated by tools/build-assets.mjs from /public. Do not edit.\nexport const FILES: Record<string, { type: string; body: string }> = ${JSON.stringify(files)};\n`);
console.log(`assets: ${Object.keys(files).length} files`);
