// Precomputes preflop equity for the 169 starting-hand types against 1-3 random opponents, so bots
// don't have to simulate on the first betting round. Writes src/preflop.ts. Run: node tools/build-preflop.ts
import { writeFileSync } from "node:fs";
import { RANKS, scoreInts } from "../src/cards.ts";

const ITER = 20000;
const rand = (n: number) => Math.floor(Math.random() * n);
export function handClass(r1: number, r2: number, suited: boolean): string {
  const [hi, lo] = r1 >= r2 ? [r1, r2] : [r2, r1];
  return hi === lo ? RANKS[hi] + RANKS[lo] : RANKS[hi] + RANKS[lo] + (suited ? "s" : "o");
}
const table: Record<string, number[]> = {};
const buf = new Int32Array(7);
for (let hi = 12; hi >= 0; hi--)
  for (let lo = hi; lo >= 0; lo--)
    for (const suited of hi === lo ? [false] : [true, false]) {
      const hole = [hi * 4, lo * 4 + (suited ? 0 : 1)];
      const eqs: number[] = [];
      for (let opps = 1; opps <= 3; opps++) {
        let won = 0;
        const rest = [...Array(52).keys()].filter((c) => !hole.includes(c));
        for (let it = 0; it < ITER; it++) {
          const need = 5 + opps * 2;
          for (let i = 0; i < need; i++) { const j = i + rand(rest.length - i); [rest[i], rest[j]] = [rest[j], rest[i]]; }
          for (let b = 0; b < 5; b++) buf[2 + b] = rest[b];
          buf[0] = hole[0]; buf[1] = hole[1];
          const mine = scoreInts(buf, 7);
          let best = true, ties = 0;
          for (let o = 0; o < opps && best; o++) {
            buf[0] = rest[5 + o * 2]; buf[1] = rest[6 + o * 2];
            const theirs = scoreInts(buf, 7);
            if (theirs > mine) best = false; else if (theirs === mine) ties++;
          }
          if (best) won += 1 / (ties + 1);
        }
        eqs.push(+(won / ITER).toFixed(3));
      }
      table[handClass(hi, lo, suited)] = eqs;
    }
writeFileSync("src/preflop.ts", `// Generated by tools/build-preflop.ts (${ITER} simulated hands per entry). Do not edit.
// Chance of winning at showdown for each starting hand against 1, 2 and 3 random opponents.
export const PREFLOP_EQUITY: Record<string, [number, number, number]> = ${JSON.stringify(table)};
`);
console.log(`wrote ${Object.keys(table).length} hand types; AA ${table.AA}, 72o ${table["72o"]}, AKs ${table.AKs}`);
