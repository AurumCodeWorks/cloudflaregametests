// Bundles /public into a single Worker script for the showroom preview.
// (Used instead of Workers static assets because this build environment's proxy rewrites the
//  asset-upload ticket. On a normal machine or Workers Builds, wrangler.preview.jsonc works as-is.)
import { readdirSync, readFileSync, writeFileSync, mkdirSync, statSync } from "node:fs";
import { join, extname } from "node:path";

const TYPES = { ".html": "text/html; charset=utf-8", ".css": "text/css; charset=utf-8", ".js": "text/javascript; charset=utf-8", ".json": "application/json", ".svg": "image/svg+xml" };
const files = {};
const walk = (dir, base = "") => {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p, `${base}/${name}`);
    else files[`${base}/${name}`] = { type: TYPES[extname(name)] ?? "application/octet-stream", body: readFileSync(p, "utf8") };
  }
};
walk("public");
const worker = `// Generated by tools/build-preview.mjs — do not edit
const FILES = ${JSON.stringify(files)};
export default {
  async fetch(request) {
    const url = new URL(request.url);
    if (url.pathname === "/" && !url.search) return Response.redirect(url.origin + "/?demo=showroom", 302);
    const f = FILES[url.pathname === "/" ? "/index.html" : url.pathname];
    if (!f) return new Response("Not found", { status: 404 });
    return new Response(f.body, { headers: { "content-type": f.type, "cache-control": "public, max-age=300" } });
  },
};
`;
mkdirSync(".preview", { recursive: true });
writeFileSync(".preview/worker.js", worker);
console.log(`bundled ${Object.keys(files).length} files, ${(worker.length / 1024).toFixed(0)} KB`);
